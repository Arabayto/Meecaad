// Turns migrations/*.sql into server/migrations.generated.ts so the Pages
// Function can apply them on first run. Cloudflare's Pages builder cannot
// import .sql files directly. Runs automatically before build and tests.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';

const files = readdirSync('migrations').filter((f) => f.endsWith('.sql')).sort();
const list = files.map((f) => `  [${JSON.stringify(f)}, ${JSON.stringify(readFileSync(`migrations/${f}`, 'utf8'))}],`).join('\n');
writeFileSync('server/migrations.generated.ts',
  `// GENERATED by scripts/embed-migrations.mjs from migrations/*.sql — do not edit.\nexport const MIGRATIONS: [string, string][] = [\n${list}\n];\n`);
console.log(`Embedded ${files.length} migration(s)`);
